"""Shared paths and loaders for the topic layer.

Topic construction reads content and keyword columns only (CONTENT_COLUMNS). No acceptance
or review field is ever loaded, so topics are fixed before any outcome analysis.

Corpus switch (environment variable ICLR_CORPUS, read once at import; POOLED_SPEC D1):
- unset or "discovery": the discovery split (data/), outputs in output/ -- unchanged.
- "pooled": discovery ∪ confirmation (data_confirmation_csv/, the released former hold-out, same schema), outputs in
  output_pooled/. load_corpus() adds `split` and is in pooled order P (stable sort of the union by year, submission_id;
  its discovery rows are the discovery order, asserted). Discovery keywords are the curated normalised lists; the
  confirmation export has none, so its raw author keywords go through keyword_map.normalize (a lookup table learned
  from discovery only). load_embeddings() stacks the discovery and released SPECTER2 caches in pooled embedded order.
  Nothing is refitted: the frozen discovery files in output/ stay the model (pooled_topics.py).
  Only POOLED_SCRIPTS may run as a topic-layer script under "pooled" (checked at import): every other builder
  (assign_topics, evaluate_topics, k_sensitivity, hindsight_check, embed_specter2*, ...) would refit on pooled data,
  overwrite the frozen copies in output_pooled/ or add pooled-order chunks to the shared CACHE (D2: never refit).
  Scripts outside research/topics (the fashion layer loads this file by path) and the topic tests are unaffected.
"""
from __future__ import annotations

import gzip
import importlib.util
import io
import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DATA = ROOT / "data"
CONFIRMATION = ROOT / "data_confirmation_csv"   # released former hold-out (pooled mode only)
CORPUS = os.environ.get("ICLR_CORPUS") or "discovery"
if CORPUS not in ("discovery", "pooled"):
    raise ValueError(f"ICLR_CORPUS must be unset, 'discovery' or 'pooled', not {CORPUS!r}")
DISCOVERY_OUTPUT = HERE / "output"              # frozen discovery outputs (model, maps, catalog); never written pooled
OUTPUT = HERE / "output_pooled" if CORPUS == "pooled" else DISCOVERY_OUTPUT
CACHE = HERE / "cache"            # embeddings live here; git-ignored, regenerated by embed_specter2.py
assert CORPUS == "discovery" or OUTPUT != DISCOVERY_OUTPUT
POOLED_SCRIPTS = ("pooled_topics.py", "keyword_map.py")      # the only topic-layer scripts that build pooled files


def check_pooled_entry(main: str | None = None) -> None:
    """Under ICLR_CORPUS=pooled refuse a topic-layer script (research/topics/**, tests excluded) other than
    POOLED_SCRIPTS as __main__ (main: that script's path; default sys.modules["__main__"].__file__)."""
    if CORPUS != "pooled":
        return
    main = getattr(sys.modules.get("__main__"), "__file__", "") if main is None else main
    path = Path(main).resolve() if main else None
    if path is None or HERE not in path.parents or HERE / "tests" in path.parents:
        return
    if not (path.parent == HERE and path.name in POOLED_SCRIPTS):
        raise SystemExit(f"{path.relative_to(HERE)} cannot run under ICLR_CORPUS=pooled: only {', '.join(POOLED_SCRIPTS)} "
                         "build the pooled topic layer (D2: the maps are frozen, never refitted)")


check_pooled_entry()

MIN_ABSTRACT_WORDS = 30           # 34 of the 36 shorter "abstracts" are placeholders such as "We have withdrawn our paper."
CONTENT_COLUMNS = ["submission_id", "year", "title", "abstract", "normalized_keywords_json", "primary_area"]
LEVELS = ("coarse", "mid", "fine")
LEVEL_SIZES = {"coarse": 20, "mid": 100, "fine": 200}
ERAS = {"2017-2020": (2017, 2020), "2021-2023": (2021, 2023), "2024-2026": (2024, 2026)}


def read_table(name: str, columns: list[str] | None = None, data: Path = DATA) -> pd.DataFrame:
    """Read an exported table with the package's null convention (\\N is null, "" is not)."""
    return pd.read_csv(data / name, keep_default_na=False, na_values=[r"\N"], usecols=columns, low_memory=False)


def load_corpus() -> pd.DataFrame:
    s = read_table("submissions.csv.gz", CONTENT_COLUMNS)
    s["keywords"] = s.normalized_keywords_json.map(lambda v: json.loads(v) if isinstance(v, str) else [])
    if CORPUS == "pooled":
        s = pooled_corpus(s)
    s["has_text"] = s.abstract.fillna("").str.split().str.len() >= MIN_ABSTRACT_WORDS
    return s


def pooled_corpus(discovery: pd.DataFrame) -> pd.DataFrame:
    """Discovery ∪ confirmation content columns in pooled order P, with `split`. Confirmation keywords =
    keyword_map.normalize(raw author keywords); its normalized_keywords_json stays as exported (null)."""
    km = keyword_map()
    c = read_table("submissions.csv.gz", CONTENT_COLUMNS + ["keywords"], CONFIRMATION)
    if c.normalized_keywords_json.notna().any():
        raise RuntimeError("The confirmation export now carries curated keywords; D3 assumes it has none")
    table = km.load_table()
    c["keywords"] = c.keywords.map(lambda raw: km.normalize(raw, table))
    c = c.astype({col: discovery[col].dtype for col in CONTENT_COLUMNS})       # the all-null column is not read as text
    both = pd.concat([discovery.assign(split="discovery"), c.assign(split="confirmation")], ignore_index=True)
    if not both.submission_id.is_unique:
        raise RuntimeError("A submission id is in both splits")
    p = both.sort_values(["year", "submission_id"], kind="stable").reset_index(drop=True)
    if not p.submission_id[p.split == "discovery"].reset_index(drop=True).equals(discovery.submission_id):
        raise RuntimeError("Pooled order P does not keep the discovery order")
    return p


def keyword_map():
    """keyword_map.py loaded by path: callers such as fashion/common.topic_layer() load this file by path too, so
    research/topics is not necessarily on sys.path."""
    spec = importlib.util.spec_from_file_location("topics_keyword_map", HERE / "keyword_map.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def embedded_corpus() -> pd.DataFrame:
    """Papers that receive a topic, in the row order of the cached embeddings."""
    s = load_corpus()
    return s[s.has_text].reset_index(drop=True)


def load_embeddings() -> tuple[np.ndarray, pd.Series]:
    ids = pd.read_csv(CACHE / "specter2_ids.csv").submission_id
    if CORPUS == "pooled":
        return pooled_embeddings(ids)
    return np.load(CACHE / "specter2.npy"), ids


def pooled_embeddings(ids: pd.Series) -> tuple[np.ndarray, pd.Series]:
    """Discovery and released SPECTER2 rows stacked, then reindexed to the pooled embedded order (raw float32)."""
    order = embedded_corpus().submission_id
    stacked = pd.concat([ids, pd.read_csv(CACHE / "specter2_released_ids.csv").submission_id], ignore_index=True)
    if not stacked.is_unique or len(stacked) != len(order) or not order.isin(stacked).all():
        raise RuntimeError("Embedding caches do not match the pooled corpus; rerun embed_specter2*.py")
    row = pd.Series(np.arange(len(stacked)), index=stacked.values)[order].values
    emb = np.vstack([np.load(CACHE / "specter2.npy"), np.load(CACHE / "specter2_released.npy")])
    return emb[row], order


def write_csv_gz(df: pd.DataFrame, path: Path) -> None:
    """Deterministic gzip (fixed mtime) so unchanged inputs give byte-identical files."""
    text = df.to_csv(index=False, lineterminator="\n")
    with path.open("wb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=6) as gz:
        with io.TextIOWrapper(gz, encoding="utf-8", newline="") as handle:
            handle.write(text)
